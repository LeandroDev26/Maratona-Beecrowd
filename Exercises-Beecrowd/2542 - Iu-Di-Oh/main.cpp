#include <iostream>

using namespace std;

int main()
{

    int n, m, l, x, y ;
    while(cin>> n)
    {
        cin>> m >> l;
        for(int i = 0 ; i < (n*m); i++)
        {
            cin>> x;
        }
        for(int k = 0 ; k < (n*l); k++)
        {
            cin>> y;
        }
    }



    return 0;
}
