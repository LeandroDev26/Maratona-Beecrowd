#include <iostream>
#include <stack>
using namespace std;

int main()
{
    int m ;
    while(cin>> m)
    {
        int valorMoeda = 0;
        stack<int> pilhaMoedas;
        for(int i = 0; i < m ; i++)
        {
            cin>> valorMoeda;
            pilhaMoedas.push(valorMoeda);
        }

    }





    return 0;
}
